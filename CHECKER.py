#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ПРОВЕРКА ОТВЕТА — замена «Stop-хука» для Arena Agent Mode (хуков здесь нет, поэтому запускаю сам ПЕРЕД отправкой).

Зачем (ход 55, research/причины-и-решение-55.md): самопроверка той же моделью ненадёжна (CRITIC, ICLR 2024), «готово» без
следа вывода — самый частый обман (69 % заявлений в одном замере), правила-пожелания теряются при сжатии контекста.
Готовое решение — завершение хода допускается, только если ответ несёт квитанции: каждое утверждение «готово» привязано
к номеру действия панели, каждое число — к источнику, каждый пункт запроса — к статусу (Evidence-Carrying Termination,
arxiv 2608.23623; Claude Code Stop-hook; spec-driven tasks.md).

  python3 память/проверка-ответа.py ответы/ХОД-N.md --ход N            # проверить (коды: 0 пройдена, 1 нет)
  python3 память/проверка-ответа.py ответы/ХОД-N.md --ход N --отчёт    # длинный ответ-отчёт: лимит 4500 знаков
  python3 память/проверка-ответа.py ответы/ХОД-N.md --ход N --сверить  # сверить строку «Проверка ответа: №K» с панелью

Проверки (детерминированные, без LLM):
  1 последняя строка «Статус: DONE|PARTIAL|NOT DONE|UNVERIFIED»      2 длина ≤ лимита (по умолчанию 2500)
  3 первая строка — вывод (≤300 знаков, без «Понял/Принял/Хорошо…»)  4 нет «извини», «должно работать» и т. п.
  5 «готово/сделано/работает/проверено…» — с № действия панели (код 0)  6 числа — с источником
  7 каждый пункт реестра лN имеет статус (СДЕЛАНО|ОТКАЗ|НУЖЕН ТЫ|ЧАСТИЧНО)  8 заявленное число запросов = строкам журнала поисков
  9 в тексте нет ключей, паролей, почт аккаунтов                      10 есть строка «Нужен ты: …»
"""
import argparse
import datetime
import glob
import hashlib
import importlib.util
import json
import os
import re
import sys
import time

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЛЕНТА = os.path.join(КОРЕНЬ, "панель", "действия.jsonl")
СТАТУС = re.compile(r"^Статус:\s*(DONE|PARTIAL|NOT DONE|UNVERIFIED)\s*$")
ПРОВЕРКА_СТРОКА = re.compile(r"^Проверка ответа:\s*№\s*(\d+)")
УТВЕРЖДЕНИЯ = re.compile(r"\b(готов\w*|сделан\w*|работает|работают|исправлен\w*|проверен\w*|подтвержд\w*|пройден\w*|выполнен\w*|залит\w*)|✓")
ОТРИЦАНИЕ = re.compile(r"\bне\s+$")
КВИТАНЦИЯ = re.compile(r"№\s*(\d{2,6})")
ВСТУПЛЕНИЯ = re.compile(r"(?i)^\W*(понял|принял|хорошо|отлично|сейчас|конечно|итак|спасибо|давай)\b")
ЗАПРЕЩЕНО = [(r"извин", "«извини» (закон 31)"), (r"должно работать", "«должно работать» (закон 19)"),
             (r"скорее всего работает", "«скорее всего работает»"), (r"наверное,? (работает|готово)", "«наверное работает»"),
             (r"вроде работает", "«вроде работает»")]
СТАТУСЫ_ПУНКТА = re.compile(r"СДЕЛАНО|ОТКАЗ|НУЖЕН ТЫ|ЧАСТИЧНО")


def действия_хода(ход):
    р = []
    if os.path.exists(ЛЕНТА):
        for с in open(ЛЕНТА, encoding="utf-8"):
            try:
                д = json.loads(с)
            except ValueError:
                continue
            if str(д.get("ход")) == str(ход):
                р.append(д)
    return р


def тело_без_квитанции(текст):
    return "\n".join(с for с in текст.split("\n") if not ПРОВЕРКА_СТРОКА.match(с.strip()))


def хеш_тела(текст):
    return hashlib.sha256(тело_без_квитанции(текст).strip().encode("utf-8")).hexdigest()


def блоки(текст):
    """Смысловые блоки: пункт списка вместе с его продолжением; строка таблицы — отдельный блок; абзац."""
    рез, текущий = [], []
    for с in текст.split("\n"):
        новый = bool(re.match(r"^\s*(\d+\.|[-*•])\s", с)) or с.lstrip().startswith("|") or с.lstrip().startswith("#")
        if not с.strip():
            if текущий:
                рез.append("\n".join(текущий))
                текущий = []
        elif новый and текущий:
            рез.append("\n".join(текущий))
            текущий = [с]
        else:
            текущий.append(с)
    if текущий:
        рез.append("\n".join(текущий))
    return рез


def пул_источников(ход, дейст, тело):
    части = []
    for д in дейст:
        части += [str(д.get("вывод") or ""), str(д.get("команда") or ""), str(д.get("запрос") or ""), str(д.get("что") or "")]
    сегодня = time.time() - 36 * 3600
    for п in glob.glob(os.path.join(КОРЕНЬ, "research", "*.md")) + glob.glob(os.path.join(КОРЕНЬ, "ответы", "реестр-*.md")):
        try:
            if os.path.getmtime(п) >= сегодня:
                части.append(open(п, encoding="utf-8", errors="ignore").read())
        except OSError:
            pass
    for м in re.finditer(r"`([^`\s]+\.(?:md|py|json|txt|jsonl))`", тело):  # файлы, названные в ответе
        п = os.path.join(КОРЕНЬ, м.group(1))
        if os.path.exists(п) and os.path.getsize(п) < 3_000_000:
            части.append(open(п, encoding="utf-8", errors="ignore").read())
    return "\n".join(части).replace("\u00a0", " ")


def числа_для_проверки(тело):
    """Числа, у которых должен быть источник: ≥3 цифр или с единицей. Не трогаем № и #, даты, годы, код в обратных кавычках, ссылки."""
    чистое = re.sub(r"`[^`]*`", " ", тело)
    чистое = re.sub(r"https?://\S+", " ", чистое)
    чистое = re.sub(r"\b\d{1,2}\.\d{1,2}\.\d{2,4}\b|\b\d{4}-\d{2}-\d{2}\b|\b\d{1,2}\.\d{2}\b(?!\d)", " ", чистое)
    найдено = []
    for м in re.finditer(r"(?<![№#\w.])(\d[\d ]*(?:[.,]\d+)?)(\s*(?:%|МБ|ГБ|КБ|тыс\.?|млн|симв\w*|знак\w*|раз|строк\w*|запрос\w*|из))?", чистое):
        число = м.group(1).strip()
        ед = (м.group(2) or "").strip()
        цифр = len(re.sub(r"\D", "", число))
        if re.fullmatch(r"20(2[4-9])", число.replace(" ", "")):
            continue
        if цифр >= 3 or (ед and ед != "из"):
            найдено.append(число.replace(" ", "") if цифр >= 4 and " " in число else число)
    return найдено


def проверки(путь, ход, лимит, режим_отчёт):
    текст = open(путь, encoding="utf-8").read()
    тело = тело_без_квитанции(текст).strip()
    дейст = действия_хода(ход)
    номера_ок = {int(д.get("н")) for д in дейст if д.get("код") == 0 and д.get("н") is not None}
    результат = []

    # 1 статус
    последняя = [с for с in тело.split("\n") if с.strip()][-1].strip() if тело else ""
    результат.append(("1 строка статуса в конце", bool(СТАТУС.match(последняя)), последняя[:70] or "пусто"))

    # 2 длина
    результат.append(("2 длина ответа", len(тело) <= лимит, "%d знаков, лимит %d%s" % (len(тело), лимит, " (режим отчёта)" if режим_отчёт else "")))

    # 3 первая строка
    первая = next((с.strip() for с in тело.split("\n") if с.strip() and not с.strip().startswith("#")), "")
    ок3 = len(первая) <= 300 and not ВСТУПЛЕНИЯ.match(первая)
    результат.append(("3 первая строка — вывод", ок3, "%d знаков: %s" % (len(первая), первая[:60])))

    # 4 запрещённое
    для_запретов = re.sub(r"[«\"']\s*извин\w*\s*[»\"']", " ", тело, flags=re.I)  # цитата закона в кавычках — не нарушение
    найдено = [имя for шаб, имя in ЗАПРЕЩЕНО if re.search(шаб, для_запретов, re.I)]
    результат.append(("4 запрещённые обороты", not найдено, ", ".join(найдено) or "нет"))

    # 5 квитанции
    плохие, красные = [], []
    for б in блоки(тело):
        if б.startswith("Статус:") or б.startswith("Нужен ты:"):
            continue
        есть_утв = False
        for м in УТВЕРЖДЕНИЯ.finditer(б):
            if ОТРИЦАНИЕ.search(б[max(0, м.start() - 8):м.start()]):
                continue
            есть_утв = True
            break
        if not есть_утв:
            continue
        кв = [int(x) for x in КВИТАНЦИЯ.findall(б)]
        if not кв:
            плохие.append(re.sub(r"\s+", " ", б)[:70])
        else:
            красные += [n for n in кв if n not in номера_ок]
    ок5 = not плохие and not красные
    пояснение5 = "все утверждения с квитанциями" if ок5 else "; ".join(
        (["без № действия: %d (напр. «%s»)" % (len(плохие), плохие[0])] if плохие else []) +
        (["№ нет в панели или код ≠ 0: %s" % sorted(set(красные))[:6]] if красные else []))
    результат.append(("5 «готово» с квитанцией панели", ок5, пояснение5))

    # 6 числа
    пул = пул_источников(ход, дейст, тело)
    пул_норм = пул.replace(" ", "")
    без_источника = []
    for ч in числа_для_проверки(тело):
        варианты = {ч, ч.replace(",", "."), ч.replace(".", ","), ч.replace(" ", "")}
        if not any(в and (в in пул or в in пул_норм) for в in варианты):
            без_источника.append(ч)
    уникальные = list(dict.fromkeys(без_источника))
    результат.append(("6 числа с источником", not уникальные,
                      "все найдены в действиях хода, запросе, свежих research/ и названных файлах" if not уникальные
                      else "нет источника у: %s" % ", ".join(уникальные[:10])))

    # 7 реестр
    реестр_путь = os.path.join(КОРЕНЬ, "ответы", "реестр-%s.md" % ход)
    if not os.path.exists(реестр_путь):
        результат.append(("7 реестр пунктов запроса", False, "нет файла ответы/реестр-%s.md" % ход))
    else:
        пункты = re.findall(r"(?m)^\s*[-*|]?\s*(л\d+)\b", open(реестр_путь, encoding="utf-8").read())
        пункты = list(dict.fromkeys(пункты))
        нет = []
        for п in пункты:
            м = re.search(r"(?i)\b%s\b" % re.escape(п), тело)
            if not м or not СТАТУСЫ_ПУНКТА.search(тело[м.end():м.end() + 260]):
                нет.append(п)
        результат.append(("7 каждый пункт реестра со статусом", bool(пункты) and not нет,
                          "пунктов %d, все со статусом" % len(пункты) if пункты and not нет else
                          ("реестр пуст" if not пункты else "нет статуса у: %s" % ", ".join(нет))))

    # 8 счётчик запросов
    журнал = os.path.join(КОРЕНЬ, "research", "поиски-%s.md" % ход)
    строк = len(re.findall(r"(?m)^\| \d+ \|", open(журнал, encoding="utf-8").read())) if os.path.exists(журнал) else 0
    заявлено = [int(м.group(2)) for м in re.finditer(
        r"(?i)(сделал\w*|выполнил\w*|выполнено|сделано|провёл|провел|всего|итого)\W{0,14}(\d{1,4})\s+(?:\w+\s+){0,2}?(?:запрос|поиск)", тело)]
    заявлено += [int(м.group(1)) for м in re.finditer(r"(?<![\d,.])(\d{1,3})\s+из\s+100\b", тело)]
    ошибки8 = [з for з in заявлено if з != строк]
    результат.append(("8 число запросов = журналу поисков", not ошибки8,
                      "в журнале хода %d строк; заявлено: %s" % (строк, заявлено or "—")))

    # 9 секреты
    спец = importlib.util.spec_from_file_location("скан", os.path.join(КОРЕНЬ, "панель", "скан-ленты.py"))
    скан = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(скан)
    секреты = скан.найти(тело)
    результат.append(("9 нет ключей, паролей, почт", not секреты, "чисто" if not секреты else "найдено: %s" % секреты))

    # 10 «Нужен ты»
    результат.append(("10 строка «Нужен ты: …»", bool(re.search(r"(?m)^Нужен ты:", тело)), ""))
    return результат, текст


def сверить(путь, ход):
    текст = open(путь, encoding="utf-8").read()
    м = next((ПРОВЕРКА_СТРОКА.match(с.strip()) for с in текст.split("\n") if ПРОВЕРКА_СТРОКА.match(с.strip())), None)
    if not м:
        print("СВЕРКА: в файле нет строки «Проверка ответа: №N»")
        return 1
    н = int(м.group(1))
    запись = next((д for д in действия_хода(ход) if д.get("н") == н), None)
    if not запись:
        print("СВЕРКА: действия №%d нет в панели хода %s" % (н, ход))
        return 1
    ждали = re.search(r"sha256 тела: ([0-9a-f]{64})", запись.get("вывод") or "")
    есть = хеш_тела(текст)
    ок = bool(ждали) and ждали.group(1) == есть and "ПРОВЕРКА ОТВЕТА: ПРОЙДЕНА" in (запись.get("вывод") or "")
    print("СВЕРКА: действие №%d · хеш тела совпадает: %s · проверка была пройдена: %s" % (
        н, "да" if ждали and ждали.group(1) == есть else "НЕТ",
        "да" if "ПРОВЕРКА ОТВЕТА: ПРОЙДЕНА" in (запись.get("вывод") or "") else "НЕТ"))
    return 0 if ок else 1


def main():
    п = argparse.ArgumentParser(description="Проверка ответа перед отправкой (замена Stop-хука)")
    п.add_argument("файл")
    п.add_argument("--ход", default=None)
    п.add_argument("--отчёт", action="store_true")
    п.add_argument("--лимит", type=int, default=None)
    п.add_argument("--сверить", action="store_true")
    а = п.parse_args()
    ход = а.ход or open(os.path.join(КОРЕНЬ, "память", "текущий-ход.txt"), encoding="utf-8").read().strip()
    if а.сверить:
        return сверить(а.файл, ход)
    лимит = а.лимит or (4500 if а.отчёт else 2500)
    рез, текст = проверки(а.файл, ход, лимит, а.отчёт)
    for имя, ок, пояснение in рез:
        print(" %s %s — %s" % ("✓" if ок else "✗", имя, пояснение))
    плохо = [и for и, ок, _ in рез if not ок]
    print("\nsha256 тела: %s" % хеш_тела(текст))
    if плохо:
        print("ПРОВЕРКА ОТВЕТА: НЕ ПРОЙДЕНА (%d из %d не выполнено)" % (len(плохо), len(рез)))
        return 1
    print("ПРОВЕРКА ОТВЕТА: ПРОЙДЕНА (%d из %d)" % (len(рез), len(рез)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
